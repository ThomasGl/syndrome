    /// Deterministic xorshift PRNG byte stream (no external RNG dependency).
    fn xorshift_bytes(len: usize, mut seed: u64) -> Vec<u8> {
        if seed == 0 {
            seed = 0xDEAD_BEEF_CAFE_F00D;
        }
        (0..len)
            .map(|_| {
                seed ^= seed << 13;
                seed ^= seed >> 7;
                seed ^= seed << 17;
                (seed >> 56) as u8
            })
            .collect()
    }

