//! Reed-Solomon erasure-recovery exporter — runs a real RS(10,4) encode,
//! erases the maximum tolerable number of data shards, and reconstructs them
//! with the real decoder, dumping every stage to JSON for the README
//! erasure-recovery animation.
//!
//! Every byte in the output comes from one real encode/erase/decode cycle:
//! [`syndrome::ReedSolomon::encode_with_avx2`] produces the parity shards,
//! four of the ten data shards are then erased, and
//! [`syndrome::ReedSolomon::decode`] reconstructs them. The reconstruction is
//! asserted byte-for-byte identical to the original before anything is
//! written — a mismatch here is a bug in this exporter or the library, and
//! the program panics rather than export data it has not verified.
//!
//! The "image" is a small grayscale bitmap generated by a deterministic
//! arithmetic pattern (concentric rings), not loaded from an external asset:
//! this keeps the exporter dependency-free and its payload fully specified by
//! the code that produces it, in the same spirit as the Knuth-multiplicative-hash
//! payloads `ldpc_convergence_export.rs` and `tests/media_reconstruction.rs` use.
//!
//! Usage: `cargo run --release --bin rs_erasure_export`
//! Output: `bench/results/rs_erasure.json`

use std::fs;
use std::io::Write as IoWrite;

use syndrome::ReedSolomon;

/// Square image side length in pixels. 80x80 = 6400 bytes, dividing evenly
/// into 10 data shards of 640 bytes each with no padding.
const SIDE: usize = 80;
const DATA_SHARDS: usize = 10;
const PARITY_SHARDS: usize = 4;
/// The maximum this code can lose and still reconstruct exactly — erasing any
/// more would make recovery impossible, which is the whole point of showing
/// exactly this many.
const SHARDS_ERASED: usize = PARITY_SHARDS;

/// Generate a deterministic grayscale test image: concentric rings around the
/// center, quantized to a handful of bands. Recognizable as a real image
/// pattern (not noise) so "erased" and "recovered" are visually obvious, and
/// fully reproducible from the formula alone.
fn generate_test_image(side: usize) -> Vec<u8> {
    let cx = (side as f32 - 1.0) / 2.0;
    let cy = cx;
    let max_r = (cx * cx + cy * cy).sqrt();
    let mut pixels = vec![0u8; side * side];
    for y in 0..side {
        for x in 0..side {
            let dx = x as f32 - cx;
            let dy = y as f32 - cy;
            let r = (dx * dx + dy * dy).sqrt() / max_r; // 0.0 (center) .. 1.0 (corner)
            // 8 rings, each a distinct band, so shard boundaries (which land
            // on whole image rows) cut across multiple rings rather than
            // aligning suspiciously with the pattern.
            let band = (r * 8.0) as u32 % 8;
            let level = 40 + band * 26; // spread across the 8-bit range
            pixels[y * side + x] = level.min(255) as u8;
        }
    }
    pixels
}

fn main() {
    let image = generate_test_image(SIDE);
    let total_bytes = image.len();
    assert_eq!(total_bytes, SIDE * SIDE);
    assert_eq!(
        total_bytes % DATA_SHARDS,
        0,
        "image size must divide evenly into data shards for this demonstration"
    );
    let shard_len = total_bytes / DATA_SHARDS;
    let rows_per_shard = SIDE / DATA_SHARDS;
    assert_eq!(
        SIDE % DATA_SHARDS,
        0,
        "image side must divide evenly into shard row-bands"
    );

    // Real RS(10,4) encoder. precompute_mul_tables() matters here exactly as
    // it did for the syndrome-py binding: encode_with_avx2 silently falls
    // back to the scalar kernel without it, still correct, just not the path
    // this benchmark/demo is meant to exercise.
    let mut rs = ReedSolomon::new(DATA_SHARDS, PARITY_SHARDS);
    rs.precompute_mul_tables();

    let data_shards: Vec<&[u8]> = image.chunks(shard_len).collect();
    assert_eq!(data_shards.len(), DATA_SHARDS);

    let mut parity_flat = vec![0u8; PARITY_SHARDS * shard_len];
    rs.encode_with_avx2(&data_shards, &mut parity_flat)
        .expect("RS(10,4) encode failed");
    let parity_shards: Vec<Vec<u8>> = parity_flat.chunks(shard_len).map(|c| c.to_vec()).collect();

    // Erase the maximum tolerable number of DATA shards, spread across the
    // image rather than contiguous, so the "corrupted" frame reads as
    // scattered damage rather than one blacked-out band. Deterministic choice
    // (every 2nd-ish shard among the first 8), not randomized, so the exact
    // erasure pattern is reproducible from this source alone.
    let erased_indices: Vec<usize> = vec![1, 3, 5, 7][..SHARDS_ERASED].to_vec();
    assert_eq!(erased_indices.len(), SHARDS_ERASED);

    let mut shards: Vec<Option<Vec<u8>>> = Vec::with_capacity(DATA_SHARDS + PARITY_SHARDS);
    for (i, d) in data_shards.iter().enumerate() {
        if erased_indices.contains(&i) {
            shards.push(None);
        } else {
            shards.push(Some(d.to_vec()));
        }
    }
    for p in &parity_shards {
        shards.push(Some(p.clone()));
    }

    // The "corrupted" view for rendering: erased shards visualized as flat
    // mid-gray (128), not part of the codec, purely a display choice made
    // explicit here rather than silently baked into the JSON as if it were
    // decoded data.
    let mut corrupted_image = image.clone();
    for &i in &erased_indices {
        let start = i * shard_len;
        corrupted_image[start..start + shard_len].fill(128);
    }

    // Real decode: reconstructs the erased data shards in place.
    rs.decode(&mut shards)
        .expect("RS(10,4) erasure decode failed");

    let mut recovered_image = vec![0u8; total_bytes];
    for (i, shard) in shards.iter().take(DATA_SHARDS).enumerate() {
        let s = shard
            .as_ref()
            .expect("all data shards must be Some after decode");
        assert_eq!(s.len(), shard_len);
        recovered_image[i * shard_len..(i + 1) * shard_len].copy_from_slice(s);
    }

    // The whole point: verify byte-for-byte before exporting anything. A
    // mismatch here means this program has a bug, and panicking is the
    // correct response — this repo does not export unverified reconstructions.
    assert_eq!(
        recovered_image, image,
        "RS(10,4) reconstruction did not exactly match the original image"
    );
    println!("Verified: {total_bytes} bytes recovered byte-for-byte identical to the original.");

    let out_dir = "bench/results";
    fs::create_dir_all(out_dir).expect("cannot create bench/results");

    let json = format!(
        r#"{{
  "side": {SIDE},
  "data_shards": {DATA_SHARDS},
  "parity_shards": {PARITY_SHARDS},
  "shard_len": {shard_len},
  "rows_per_shard": {rows_per_shard},
  "erased_shard_indices": {erased_indices:?},
  "original_image": {image:?},
  "corrupted_image": {corrupted_image:?},
  "recovered_image": {recovered_image:?},
  "byte_perfect": true
}}
"#
    );

    let out_path = format!("{out_dir}/rs_erasure.json");
    let mut f = fs::File::create(&out_path).expect("cannot create rs_erasure.json");
    f.write_all(json.as_bytes()).expect("write failed");
    println!("Wrote {out_path}");
}
